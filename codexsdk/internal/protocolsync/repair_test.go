type repairExecutorFixture struct {
	preflight error
	run       func(context.Context, string, string) (codexexec.Result, error)
}

func (f repairExecutorFixture) Preflight(context.Context) error { return f.preflight }
func (f repairExecutorFixture) Run(c context.Context, p, s string) (codexexec.Result, error) {
	return f.run(c, p, s)
}
func repairFixture(t *testing.T) RepairRequest {
	t.Helper()
	root := initSyncRepo(t, oldSHA, "rust-v0.140.0", KindStableTag)
	candidate := filepath.Join(t.TempDir(), "candidate")
	writeCandidateFixture(t, candidate, newSHA)
	digest, err := candidateDigest(candidate)
	if err != nil {
		t.Fatal(err)
	}
	return RepairRequest{ResumeRequest: ResumeRequest{RepoRoot: root, ModuleRoot: filepath.Join(root, "codexsdk"), CandidateDir: candidate, CandidateSHA256: digest, TargetRef: "rust-v0.141.0", TargetKind: KindStableTag, TargetSHA: newSHA}, CheckpointDir: filepath.Join(t.TempDir(), "checkpoint"), MaxRounds: 6}
}
func readRepairCheckpoint(t *testing.T, dir string) repairCheckpoint {
	t.Helper()
	var cp repairCheckpoint
	raw, err := os.ReadFile(filepath.Join(dir, "checkpoint.json"))
	if err != nil {
		t.Fatal(err)
	}
	if err = json.Unmarshal(raw, &cp); err != nil {
		t.Fatal(err)
	}
	return cp
}
func TestRepairSequentialUnknownShapesAndValidationFeedback(t *testing.T) {
	req := repairFixture(t)
	round := 0
	observed := 0
	shapes := []string{"nested constrained union", "nullable recursive map", "required object extension"}
	req.Executor = repairExecutorFixture{run: func(_ context.Context, prompt, session string) (codexexec.Result, error) {
		if round > 0 && session != "exact-session" {
			t.Fatal("not exact resume")
		}
		if round > 0 && !strings.Contains(readFeedbackPrompt(t, prompt), "controller_failure") {
			t.Fatal("missing oracle feedback")
		}
		round++
		writeFile(t, filepath.Join(req.RepoRoot, "codexsdk/internal/protocolgen/fixture.go"), fmt.Sprintf("package protocolgen // proposal %d\n", round))
		// Prior failed construction must not appear in the model workspace.
		if _, err := os.Stat(filepath.Join(req.RepoRoot, "codexsdk/protocolv2/protocol_types.gen.go")); !os.IsNotExist(err) {
			t.Fatal("generated bytes leaked into proposal")
		}
		return codexexec.Result{Status: "completed", SessionID: "exact-session"}, nil
	}}
	req.Oracle = func(_ context.Context, r ResumeRequest) (SyncResult, []byte, error) {
		observed++
		if r.CandidateDir == req.CandidateDir {
			t.Fatal("mutable source candidate used")
		}
		if observed <= len(shapes) {
			return SyncResult{Stage: "replan", FailureCategory: FailureUnsupported, Issue: &protocolupgrade.PlanIssue{Stage: "codegen", Path: "new/shape", Reason: shapes[observed-1]}}, nil, errors.New(shapes[observed-1])
		}
		if observed == 4 {
			return SyncResult{Stage: "verification"}, nil, errors.New("focused invariant failed")
		}
		return SyncResult{Outcome: OutcomeApplied}, nil, nil
	}
	result, err := Repair(context.Background(), req)
	if err != nil || result.Outcome != OutcomeApplied || round != 5 {
		t.Fatalf("result=%+v rounds=%d err=%v", result, round, err)
	}
	if cp := readRepairCheckpoint(t, req.CheckpointDir); cp.Status != "verified" {
		t.Fatal(cp)
	}
}
func TestRepairBlocksAndRetainsCheckpoint(t *testing.T) {
	for _, mode := range []string{"404", "cancel", "no-progress", "scope", "oracle-mutation", "oracle-contract", "budget"} {
		t.Run(mode, func(t *testing.T) {
			req := repairFixture(t)
			calls := 0
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			fixture := repairExecutorFixture{run: func(_ context.Context, _, _ string) (codexexec.Result, error) {
				calls++
				writeFile(t, filepath.Join(req.RepoRoot, "codexsdk/internal/protocolgen/fixture.go"), "package protocolgen\n")
				if mode == "cancel" {
					cancel()
					return codexexec.Result{Status: "cancelled", SessionID: "same"}, context.Canceled
				}
				if mode == "scope" {
					writeFile(t, filepath.Join(req.RepoRoot, "codexsdk/internal/protocolsync/sync.go"), "tamper")
				}
				return codexexec.Result{Status: "completed", SessionID: "same"}, nil
			}}
			if mode == "404" {
				fixture.preflight = errors.New("endpoint_not_found")
			}
			if mode == "budget" {
				req.MaxRounds = 1
			}
			req.Executor = fixture
			req.Oracle = func(_ context.Context, _ ResumeRequest) (SyncResult, []byte, error) {
				if mode == "oracle-contract" {
					return SyncResult{Stage: "oracle_contract", FailureCategory: FailureUnsupported}, nil, errors.New("uncovered source /properties/newShape")
				}
				if mode == "oracle-mutation" {
					writeFile(t, filepath.Join(req.RepoRoot, "codexsdk/internal/protocolgen/fixture.go"), "mutated by test")
				}
				return SyncResult{Stage: "verification"}, nil, errors.New("failed proof")
			}
			if _, err := Repair(ctx, req); err == nil {
				t.Fatal("accepted failure")
			}
			cp := readRepairCheckpoint(t, req.CheckpointDir)
			want := map[string]string{"404": "blocked", "cancel": "cancelled", "no-progress": "no_progress", "scope": "blocked", "oracle-mutation": "blocked", "oracle-contract": "blocked", "budget": "exhausted"}[mode]
			if cp.Status != want {
				t.Fatalf("status=%s want %s", cp.Status, want)
			}
			if mode == "oracle-contract" && (calls != 1 || cp.Stage != "oracle_contract" || !strings.Contains(cp.Diagnostic, "/properties/newShape")) {
				t.Fatalf("trusted capability failure lost or retried: calls=%d checkpoint=%+v", calls, cp)
			}
			if mode == "404" && calls != 0 {
				t.Fatal("provider block invoked agent")
			}
			if mode == "no-progress" && calls != 2 {
				t.Fatalf("calls=%d", calls)
			}
		})
	}
}
func TestRepairCheckpointRecoveryRejectsStaleAndTamperedState(t *testing.T) {
	for _, mode := range []string{"valid", "base", "target", "candidate", "proposal", "control"} {
		t.Run(mode, func(t *testing.T) {
			req := repairFixture(t)
			req.Executor = repairExecutorFixture{preflight: errors.New("cancelled")}
			writeFile(t, filepath.Join(req.RepoRoot, "codexsdk/internal/protocolgen/fixture.go"), "package protocolgen\n")
			_, _ = Repair(context.Background(), req)
			cp := readRepairCheckpoint(t, req.CheckpointDir)
			// Clean accepted checkout exactly as a later workflow would obtain it.
			if err := runGit(req.RepoRoot, "reset", "--hard", "HEAD"); err != nil {
				t.Fatal(err)
			}
			if err := runGit(req.RepoRoot, "remote", "add", "origin", req.RepoRoot); err != nil {
				t.Fatal(err)
			}
			target := newSHA
			switch mode {
			case "base":
				writeFile(t, filepath.Join(req.RepoRoot, "README.md"), "new base")
				runGitInitCommit(t, req.RepoRoot, "advance")
			case "target":
				target = oldSHA
			case "candidate":
				writeFile(t, filepath.Join(req.CheckpointDir, "candidate/schema/ClientRequest.json"), "tampered")
			case "proposal":
				writeFile(t, filepath.Join(req.CheckpointDir, "proposal.patch"), "tampered")
			case "control":
				patch := []byte("diff --git a/README.md b/README.md\n--- a/README.md\n+++ b/README.md\n@@ -1 +1 @@\n-# fixture\n+tampered\n")
				cp.ProposalSHA256 = repairDigest(patch)
				raw, _ := json.Marshal(cp)
				writeFile(t, filepath.Join(req.CheckpointDir, "checkpoint.json"), string(raw))
				writeFile(t, filepath.Join(req.CheckpointDir, "proposal.patch"), string(patch))
			}
			lookup := fakeLookuper{byPattern: map[string]string{"refs/tags/rust-v0.141.0": target + "\trefs/tags/rust-v0.141.0", "refs/tags/rust-v0.141.0^{}": target + "\trefs/tags/rust-v0.141.0^{}"}}
			got, err := RestoreRepair(req.RepoRoot, req.CheckpointDir, "origin", "main", lookup, nil)
			if (err == nil) != (mode == "valid") {
				t.Fatalf("mode %s got %+v error %v", mode, got, err)
			}
		})
	}
}
